    else
        g, ϕg0 = get_hybridproblem_MLapplicator(prob; scenario)
        g(xM, prob.ϕg) # TODO separate state, avoid prob.ϕg
    end
    get_cholesky_correlation_Ms(prob.approx, ϕq, cor_ends.M, ϕm)
end

function get_cholesky_correlation_Ms(
