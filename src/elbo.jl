function sample_posterior(rng::AbstractRNG, g, ϕ::AbstractVector, xM::AbstractMatrix;
    int_ϕg_ϕq::AbstractComponentArrayInterpreter,
    int_ϕq::AbstractComponentArrayInterpreter,
    transP, transM,
    n_sample_pred,
    n_sample_ranef,
    cdev,
    cor_ends,
    pbm_covar_indices,
    is_inferred::Val{is_infer} = Val(false),
    is_testmode,
    approx::AbstractHVIApproximation,
    itrain_sites,
    ranef::AbstractRandomEffectsComputer,
    frac_cluster::AbstractVector,
) where is_infer
    ζsP_gpu, ζsMs_tr_gpu, σ = is_infer ? 
    Test.@inferred(generate_ζ(approx, rng, g, CA.getdata(ϕ), CA.getdata(xM);
        int_ϕg_ϕq, int_ϕq,
        n_MC=n_sample_pred, n_sample_ranef,
        cor_ends, pbm_covar_indices, is_testmode, itrain_sites, ranef,
        )) :
    generate_ζ(approx, rng, g, CA.getdata(ϕ), CA.getdata(xM);
        int_ϕg_ϕq, int_ϕq,
        n_MC=n_sample_pred, n_sample_ranef,
        cor_ends, pbm_covar_indices, is_testmode, itrain_sites, ranef,
        ) 
    ζsP = cdev(ζsP_gpu)
    ζsMs_tr = cdev(ζsMs_tr_gpu)
    # logdetΣ = 2 * sum(log.(σ))
    # entropy_ζ = entropy_MvNormal(length(σ), logdetΣ)
    n_θP = size(ζsP,1)
    n_θM = size(ζsMs_tr, 2)
    n_site = size(ζsMs_tr, 1)
    entropy_ζ = is_infer ? 
        Test.@inferred(compute_entropyζ_from_σ(σ; frac_cluster, n_θP, n_θM, n_site)) :
        compute_entropyζ_from_σ(σ; frac_cluster, n_θP, n_θM, n_site)
    trans_mP = StackedArray(transP, size(ζsP, 2))
    trans_mMs = StackedArray(transM, size(ζsMs_tr, 1) * size(ζsMs_tr, 3))
    θsP, θsMs_tr, logjacs_P, logjacs_Ms = is_infer ? 
        #transform_and_logjac_ζ    
        Test.@inferred(transform_and_logjacs_ζs(ζsP, ζsMs_tr; trans_mP, trans_mMs)) :
        transform_and_logjacs_ζs(ζsP, ζsMs_tr; trans_mP, trans_mMs)
    (; θsP, θsMs_tr, entropy_ζ, ζsP, ζsMs_tr, logjacs_P, logjacs_Ms)
end


"""
Generate samples of (inv-transformed) model parameters, ζ, 
and the vector of standard deviations, σ, i.e. the diagonal of the cholesky-factor.

Adds the MV-normally distributed residuals, retrieved by `sample_ζresid_norm`
to the means extracted from parameters and predicted by the machine learning
model. 

The output shape of size `(n_site x n_par x n_MC)` is tailored to iterating
each MC sample and then transforming each parameter on block across sites.
"""
function generate_ζ(
    #approx::Union{AbstractMeanHVIApproximation, AbstractMeanVarSepHVIApproximation}, 
    approx::AbstractHVIApproximation, 
    rng::AbstractRNG, 
    g, ϕ::AbstractVector{FT}, xM::MT;
    int_ϕg_ϕq::AbstractComponentArrayInterpreter,
    int_ϕq::AbstractComponentArrayInterpreter,
    ranef::AbstractRandomEffectsComputer,
    n_MC=3, 
    n_sample_ranef = size(xM,2) ÷ 10,
    cor_ends, pbm_covar_indices,
    is_testmode,
    itrain_sites, # = 1:size(xM,2),
    ) where {FT,MT}
    n_site = size(xM,2)
    # see documentation of neg_elbo_gtf
    ϕc = int_ϕg_ϕq(CA.getdata(ϕ))
    #VT= typeof(@view(ϕ[1:1]))
    ϕg = CA.getdata(ϕc[Val(:ϕg)])
    ϕq = CA.getdata(ϕc[Val(:ϕq)])
    ϕqc = int_ϕq(ϕq)
    μ_ζP = CA.getdata(ϕqc[Val(:μP)])
    # first pass only : append μ_ζP_to covars, need ML prediction for magnitude of ζMs
    # TODO replace pbm_covar_indices by ComponentArray? dimensions to be type-inferred?
    n_site_pred = size(xM, 2) 
    xMP0 = _append_each_covars(xM, CA.getdata(μ_ζP), pbm_covar_indices)
    ϕm0 = g(xMP0, ϕg; is_testmode)
    ζP_resids, ζMs_parfirst_resids, σ = sample_ζresid_norm(approx, rng, 
        itrain_sites, ϕm0, ϕq; n_MC, cor_ends, int_ϕq)
    # if itrain_sites is given add known random effect to μ_ζMs_g0
    #    if random effect is unknown, sample for each group in ζMs_parfirst_resids
    ϕq_ranef = ϕqc[Val(:ranef)]
    n_θm = size(ζMs_parfirst_resids, 1)
    μ_ζMs0_tr = ϕm0[1:n_θm, :]'
    # if random effect is kown, i.e. itrain_sites is provided, add to ζMs_resids
    #    otherwise add the same sampled random effect for n_sample_ranef sites to ζMs_resids
    ζMs_parfirst_ranef_resids = if !isempty(itrain_sites) && !iszero(itrain_sites[1])
        # random effect (same for all samples, in 3rd dimenstion) is recycled
        #   adding it to μ is not valid, becase μ may be resampled given ζPi covariates
        add_ranef(ranef, ζMs_parfirst_resids, ϕq_ranef, itrain_sites) 
    else
        # TODO move n_distict_ranef and i_col out of the loop
        n_distict_ranef = ceil(Int, n_site / n_sample_ranef)
        i_col = generate_repeated_integers(n_site_pred, n_sample_ranef)
        β_distinct = sample_ranef(ranef, ϕq_ranef, n_distict_ranef, n_MC)
        β = β_distinct[:,i_col,:]
        @assert size(β) == size(ζMs_parfirst_resids)
        ζMs_parfirst_resids .+ β
    end         
    # if !all(isfinite.(μ_ζMs0))
    #     @show μ_ζMs0
    #     is_infinite_ϕg = !all(isfinite.(ϕg))
    #     @show is_infinite_ϕg
    #     error("encountered non-finite μ_ζMs0")
    # end
    ζsP = isempty(μ_ζP) ? ζP_resids : (μ_ζP .+ ζP_resids)  # n_par x n_MC 
    if pbm_covar_indices isa SA.SVector{0}
        # do not need to predict again but just add the residuals to μ_ζP and μ_ζMs
        #ζsP = μ_ζP .+ ζP_resids  # n_par x n_MC # .+ on empty view does not work
        ζsMs_tr = μ_ζMs0_tr .+ permutedims(ζMs_parfirst_ranef_resids, (2, 1, 3)) # n_site x n_par x n_MC
        # if any(ζsMs[:,2,:] .> 80.0)
        #     @show ζsMs
        #     @show ζMs_parfirst_ranef_resids
        #     @show ϕc.ϕq.coef_logσ2_ζMs
        #     error("encountered scaled residual outside envisoned range. Debug") 
        # end
    else
        #ζP, rMs = first(zip(eachcol(ζsP), eachslice(ζMs_parfirst_ranef_resids;dims=3)))
        ζsMs_tr_vec = map(eachcol(ζsP), eachslice(ζMs_parfirst_ranef_resids; dims=3)) do ζP, rMs
            # second pass: append ζP rather than μ_ζP to covars to xM
            xMP = _append_each_covars(xM, CA.getdata(ζP), pbm_covar_indices)
            ϕm = g(xMP, ϕg; is_testmode)
            μ_ζMs_gt = ϕm[1:n_θm, :]
            # randeom effect already in rMs
            ζMs_tr = (μ_ζMs_gt' .+ rMs')  # already transform to par-last form
            ζMs_tr
