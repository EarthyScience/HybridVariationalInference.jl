"""
    predict_hvi([rng], prob::AbstractHybridProblem)

Prediction function for hybrid variational inference parameter model. 

## Arguments
- `prob`: The problem for which to predict

## Keyword arguments
- `scenario`
- `n_sample_pred`
- `n_sample_ranef`: how many samples shall share the same random effect
- `xM`: covariates for the machine-learning model (ML): Matrix (n_θM x n_site_pred).
  Possibility to override the default from `get_hybridproblem_train_dataloader`.
- `xP`: model drivers for process based model (PBM): Matrix with (n_site_pred) rows.
  Possibility to override the default from `get_hybridproblem_train_dataloader`.
- `frac_cluster`: how many sites in a cluster does each site in xP represent?
  Default one, does not regards clusters. If influences the value of returned `entropy_ζ`.
  Hence, it should be adjuter, for recomputing elbo components of observed sites.

Returns an NamedTuple `(; y, θsP, θsMs_tr, entropy_ζ)` with entries
- `y`: Array `(n_obs, n_site, n_sample_pred)` of model predictions.
- `addq`: Array `(n_addq, n_site, n_sample_pred)` of additional quantities computed 
  by the PBM.
- `θsP`: ComponentArray `(n_θP, n_sample_pred)` of PBM model parameters
  that are kept constant across sites.
- `θsMs_tr`: ComponentArray `(n_site, n_θM, n_sample_pred)` of PBM model parameters
  that vary by site.
- `entropy_ζ`: The entropy of the log-determinant of the transformation of 
  the set of model parameters, which is involved in uncertainty quantification.
- `ζsP`: ComponentArray `(n_θP, n_sample_pred)` of PBM model parameters
  that are kept constant across sites at the unconstrained scale.
- `ζsMs_tr`: ComponentArray `(n_site, n_θM, n_sample_pred)` of PBM model parameters
  that vary by site at the unconstrained scale.
- `penalties`: output of problems penalty computer average across samples as a ComponentVector
- `logjacs_P`: Vector `(n_sample_pred)` of logarithm of determinant 
    of the transformation of ζP
  that are kept constant across sites at the unconstrained scale.
- `logjacs_Ms`: Matrix `(n_site, n_sample_pred)` of logarithm of determinant 
    of the transformation of ζMs

Note that for some approximations, such as `MeanVarSepHVIApproximation`, 
`prob.ϕq` contains uncertainty parameters that are specific to sites. 
For a proper prediction for new sites, update `prob.ϕq` before appropriately.
If xM and xP is unspecified, the problem's sites are used and `prob.ϕq` is consistent.
If predicting for a subset of training sites, specify keyword argument `itrain_sites`,
Otherwise the default of empty vector of site-ids is used.
"""
function predict_hvi(rng::AbstractRNG, prob::AbstractHybridProblem; scenario=Val(()), 
    gdevs = get_gdev_MP(scenario), 
    xM = nothing, xP = nothing,
    is_testmode = true,
    itrain_sites = Int[],
    n_sample_pred = 200,
    n_sample_ranef = n_sample_pred ÷ 10,
    frac_cluster = ones(eltype(prob.ϕg), 0),
    kwargs...
    )
    # update to HybridProblem, if empty defaults were used
    xM, xP, itrain_sites, frac_cluster = initX_from_prob(prob; scenario, gdevs,  
        xM, xP, itrain_sites, frac_cluster)
    # sample_posterior required consistent prob.ϕq and xM
    (; θsP, θsMs_tr, entropy_ζ, ζsP, ζsMs_tr, logjacs_P, logjacs_Ms) = sample_posterior(
        rng, prob, xM; 
        scenario, gdevs, is_testmode, itrain_sites, n_sample_pred, n_sample_ranef,
        frac_cluster,
        kwargs...)
    #
    n_site, n_batch = get_hybridproblem_n_site_and_batch(prob; scenario)
    n_site_pred = size(xP, 2)
    f_batch = get_hybridproblem_PBmodel(prob; scenario)
    f = n_site_pred == n_batch ? f_batch : create_nsite_applicator(f_batch, n_site_pred)
    if gdevs.gdev_P isa MLDataDevices.AbstractGPUDevice
        f_dev = gdevs.gdev_P(f)#fmap(gdevs.gdev_P, f)
    else
        f_dev = f
    end
    #y = apply_process_model(θsP, θsMs_tr, f_dev, xP)
    (y, addq) = f_dev(θsP, θsMs_tr, xP)
    # compute penalties
    penalty_computer = get_hybridproblem_penalty_computer(prob; scenario)
    pt = get_hybridproblem_par_templates(prob; scenario)
    intθP = ComponentArrayInterpreter(pt.θP)
    intθMs = ComponentArrayInterpreter((n_site_pred,), pt.θM)
    #i_MC = 1
    #MAYBE use StaticArrays from NamedTuple and initial value
    penalties_sum = mapreduce((x,y) -> x .+ y, axes(y,3)) do i_MC
        CA.ComponentVector(
            compute_penalty(penalty_computer,
            y[:,:,i_MC], addq[:,:,i_MC], intθMs(θsMs_tr[:,:,i_MC]), intθP(θsP[:,i_MC]), itrain_sites, 
            prob.ϕq)
            ) # TODO separate from prob
    end
    # reshape into ComponentMatrix with site rows
    # intPen = ComponentArrayInterpreter((n_site_pred,), 
    #     CA.ComponentVector(NamedTuple{keys(penalties_sum)}(0.0 for _ in keys(penalties_sum)))
    # )
    # penalties = intPen(CA.getdata(penalties_sum)) ./ n_sample_pred
    penalties = reshape_penalty_matrix(penalties_sum) ./ n_sample_pred
    (; y, addq, θsP, θsMs_tr, entropy_ζ, ζsP, ζsMs_tr, penalties, logjacs_P, logjacs_Ms)
end

function initX_from_prob(prob; scenario, gdevs, xM, xP, itrain_sites, frac_cluster)
    if isnothing(xM) || isnothing(xP)
        dl = get_hybridproblem_train_dataloader(prob; scenario)
        dl_dev = gdev_hybridproblem_dataloader(dl; gdevs)
        xM_dl, xP_dl = dl_dev.data[1:2]
        itrain_sites = isempty(itrain_sites) ? (1:size(xM_dl, 2)) : itrain_sites
        xP = isnothing(xP) ? xP_dl[:,itrain_sites] : xP
        xM = isnothing(xM) ? xM_dl[:,itrain_sites] : xM
    end
    n_site_pred = size(xM,2) 
    if isempty(frac_cluster)
        frac_cluster = ones(eltype(frac_cluster), n_site_pred)
    end
    xM, xP, itrain_sites, frac_cluster
end


